-- Disposable discovery cache: TMDB TV title -> AniList entry (or confirmed no match). No user data.
CREATE TABLE anilist_mappings (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 resource_type varchar(10) NOT NULL CHECK (resource_type IN ('MOVIE','TV')),
 tmdb_id bigint NOT NULL,
 matched boolean NOT NULL,
 anilist_id bigint, mal_id bigint, format varchar(20),
 adult boolean NOT NULL DEFAULT false,
 genres varchar(1000), tags varchar(4000),
 mean_score integer, popularity integer, episodes integer, season_year integer,
 fetched_at timestamp(6) NOT NULL,
 CONSTRAINT uk_anilist_mapping_identity UNIQUE(resource_type, tmdb_id)
);

GRANT SELECT, INSERT, UPDATE, DELETE ON anilist_mappings TO "${runtimeRole}";
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA movienight TO "${runtimeRole}";
