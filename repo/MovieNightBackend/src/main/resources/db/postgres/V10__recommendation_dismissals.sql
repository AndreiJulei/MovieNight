-- Personal recommendations: titles a user removed ("Not interested"). Permanent until undone;
-- every recomputation and read excludes them, so the next candidate takes the freed place.
CREATE TABLE recommendation_dismissals (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES users(id),
 tmdb_id bigint NOT NULL,
 media_type varchar(20) NOT NULL,
 created_at timestamp(6) NOT NULL,
 CONSTRAINT uk_rec_dismissal_user_title UNIQUE (user_id, media_type, tmdb_id)
);

GRANT SELECT, INSERT, UPDATE, DELETE ON recommendation_dismissals TO "${runtimeRole}";
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA movienight TO "${runtimeRole}";
