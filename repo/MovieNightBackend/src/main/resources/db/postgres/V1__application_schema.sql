-- Supported preceding PostgreSQL schema. V2 expands notes and adds rating integrity.
CREATE TABLE users (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email varchar(100) NOT NULL UNIQUE, username varchar(50) NOT NULL UNIQUE,
 display_name varchar(50) NOT NULL, password varchar(255) NOT NULL,
 reset_code varchar(10), reset_code_expires_at timestamp(6),
 role varchar(30) NOT NULL DEFAULT 'ROLE_USER', needs_recommendation_refresh boolean NOT NULL DEFAULT true,
 personal_recommendation_state varchar(255), personal_recommendation_limitations varchar(1000),
 created_at timestamp(6) NOT NULL, updated_at timestamp(6)
);
CREATE INDEX idx_user_display_name ON users(display_name);
CREATE TABLE movies (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tmdb_id bigint, imdb_id varchar(30),
 title varchar(300) NOT NULL, release_year integer, overview text, poster_url varchar(1000),
 backdrop_url varchar(1000), genres varchar(200), runtime_minutes integer, trailer_key varchar(100),
 director varchar(300), cast_members varchar(500), media_type varchar(20) NOT NULL,
 resource_type varchar(10) NOT NULL CHECK (resource_type IN ('MOVIE','TV')),
 seasons_count integer, episodes_count integer, imdb_rating double precision,
 rotten_tomatoes_rating integer, tmdb_vote_average double precision, tmdb_vote_count integer,
 created_at timestamp(6) NOT NULL, updated_at timestamp(6)
);
CREATE UNIQUE INDEX idx_movie_tmdb_id ON movies(resource_type,tmdb_id);
CREATE INDEX idx_movie_title ON movies(title);
CREATE TABLE user_movie_entries (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES users(id), movie_id bigint NOT NULL REFERENCES movies(id),
 status varchar(20) NOT NULL CHECK (status IN ('WATCHLIST','WATCHED','DROPPED')),
 personal_rating double precision, notes varchar(255), watched_at timestamp(6),
 created_at timestamp(6) NOT NULL, updated_at timestamp(6),
 CONSTRAINT uk_user_movie UNIQUE(user_id,movie_id)
);
CREATE INDEX idx_user_status ON user_movie_entries(user_id,status);
CREATE INDEX idx_movie_ratings ON user_movie_entries(movie_id,personal_rating);
CREATE TABLE custom_lists (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id bigint NOT NULL REFERENCES users(id),
 title varchar(150) NOT NULL, description text, is_public boolean NOT NULL DEFAULT false,
 created_at timestamp(6) NOT NULL, updated_at timestamp(6)
);
CREATE INDEX idx_custom_list_user ON custom_lists(user_id);
CREATE INDEX idx_custom_list_public ON custom_lists(is_public);
CREATE TABLE custom_list_entries (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 custom_list_id bigint NOT NULL REFERENCES custom_lists(id), movie_id bigint NOT NULL REFERENCES movies(id),
 position integer NOT NULL, added_at timestamp(6) NOT NULL,
 CONSTRAINT uk_custom_list_movie UNIQUE(custom_list_id,movie_id)
);
CREATE INDEX idx_entry_list_position ON custom_list_entries(custom_list_id,position);
CREATE TABLE friendships (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES users(id), friend_id bigint NOT NULL REFERENCES users(id),
 accepted boolean NOT NULL DEFAULT false, created_at timestamp(6) NOT NULL,
 CONSTRAINT uk_user_friend UNIQUE(user_id,friend_id)
);
CREATE INDEX idx_friendship_user ON friendships(user_id);
CREATE INDEX idx_friendship_friend ON friendships(friend_id);
CREATE TABLE cached_movie_list (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 media_type varchar(20) NOT NULL, resource_type varchar(10) NOT NULL CHECK (resource_type IN ('MOVIE','TV')),
 list_type varchar(30) NOT NULL, tmdb_id bigint NOT NULL, title varchar(255) NOT NULL,
 poster_path varchar(255), vote_average double precision, release_date varchar(255),
 rank_order integer NOT NULL, cached_at timestamp(6) NOT NULL
);
CREATE INDEX idx_cache_type_rank ON cached_movie_list(list_type,rank_order);
CREATE INDEX idx_cache_media_type_rank ON cached_movie_list(media_type,list_type,rank_order);
CREATE INDEX idx_cache_tmdb_id ON cached_movie_list(tmdb_id);
CREATE TABLE movie_similarity (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tmdb_id bigint NOT NULL,
 neighbor_tmdb_id bigint NOT NULL, score double precision NOT NULL
);
CREATE INDEX idx_sim_tmdb_id ON movie_similarity(tmdb_id);
CREATE UNIQUE INDEX idx_sim_tmdb_neighbor ON movie_similarity(tmdb_id,neighbor_tmdb_id);
CREATE TABLE personalized_recommendations (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id bigint NOT NULL REFERENCES users(id),
 tmdb_id bigint NOT NULL, media_type varchar(20) NOT NULL,
 resource_type varchar(10) NOT NULL CHECK (resource_type IN ('MOVIE','TV')),
 title varchar(255) NOT NULL, poster_path varchar(255), vote_average double precision,
 release_year integer, score double precision NOT NULL, rank_order integer NOT NULL,
 created_at timestamp(6) NOT NULL
);
CREATE INDEX idx_rec_user_rank ON personalized_recommendations(user_id,rank_order);
CREATE UNIQUE INDEX idx_rec_user_tmdb ON personalized_recommendations(user_id,resource_type,tmdb_id);
CREATE TABLE webhook_subscriptions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id bigint NOT NULL REFERENCES users(id),
 target_url varchar(1000) NOT NULL, secret varchar(128) NOT NULL, description varchar(255),
 events varchar(500) NOT NULL DEFAULT '*', is_active boolean NOT NULL DEFAULT true,
 consecutive_failures integer NOT NULL DEFAULT 0, last_delivery_at timestamp(6), last_delivery_status integer,
 created_at timestamp(6) NOT NULL, updated_at timestamp(6)
);
CREATE INDEX idx_webhook_user ON webhook_subscriptions(user_id);
CREATE INDEX idx_webhook_active ON webhook_subscriptions(is_active);
CREATE TABLE webhook_delivery_logs (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 subscription_id bigint NOT NULL REFERENCES webhook_subscriptions(id),
 event_id varchar(64) NOT NULL, event_type varchar(64) NOT NULL, payload text,
 response_status integer, response_body text, duration_ms bigint, success boolean NOT NULL,
 attempt_count integer NOT NULL DEFAULT 1, created_at timestamp(6) NOT NULL
);
CREATE INDEX idx_delivery_sub ON webhook_delivery_logs(subscription_id);
CREATE INDEX idx_delivery_created ON webhook_delivery_logs(created_at);
